func TestSettingsTypes(t *testing.T) {
	configuration := &couchbasev2.EncryptionAtRestUsageConfiguration{KeyName: "configuration"}
	audit := &couchbasev2.EncryptionAtRestUsageConfiguration{KeyName: "audit"}
	log := &couchbasev2.EncryptionAtRestUsageConfiguration{KeyName: "log"}

	spec := &couchbasev2.EncryptionAtRestSpec{Configuration: configuration, Audit: audit, Log: log}

	cases := []struct {
		name       string
		serverName string
		keyUsage   string
		settings   *couchbasev2.EncryptionAtRestUsageConfiguration
		usage      couchbasev2.CouchbaseEncryptionKeyUsage
	}{
		{
			name:       constants.EncryptionAtRestUsageConfiguration,
			serverName: "config",
			keyUsage:   couchbaseutil.EncryptionKeyUsageConfigEncryption,
			settings:   configuration,
			usage:      couchbasev2.CouchbaseEncryptionKeyUsage{Configuration: true},
		},
		{
			name:       constants.EncryptionAtRestUsageAudit,
			serverName: "audit",
			keyUsage:   couchbaseutil.EncryptionKeyUsageAuditEncryption,
			settings:   audit,
			usage:      couchbasev2.CouchbaseEncryptionKeyUsage{Audit: true},
		},
		{
			name:       constants.EncryptionAtRestUsageLog,
			serverName: "log",
			keyUsage:   couchbaseutil.EncryptionKeyUsageLogsEncryption,
			settings:   log,
			usage:      couchbasev2.CouchbaseEncryptionKeyUsage{Log: true},
		},
	}

	assert.Len(t, SettingsTypes, len(cases))

	for i, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			settingsType := SettingsTypes[i]

			assert.Equal(t, tc.name, settingsType.Name)
			assert.Equal(t, tc.serverName, settingsType.ServerName)
			assert.Equal(t, tc.keyUsage, settingsType.KeyUsage)
			assert.Same(t, tc.settings, settingsType.SettingsFor(spec))
			assert.Nil(t, settingsType.SettingsFor(nil))
			assert.True(t, settingsType.KeyAllows(tc.usage))
			assert.False(t, settingsType.KeyAllows(couchbasev2.CouchbaseEncryptionKeyUsage{Key: true, AllBuckets: true}))
		})
	}
}

func TestCredentialsFor(t *testing.T) {
	const mountDir = "/opt/couchbase/var/lib/couchbase/key/"

	cases := []struct {
		name        string
		spec        couchbasev2.CouchbaseEncryptionKeySpec
		wantPaths   map[string]string
		wantValues  []string
		wantSpecRef string
	}{
		{
			name: "auto generated reads nothing",
			spec: couchbasev2.CouchbaseEncryptionKeySpec{KeyType: couchbasev2.CouchbaseEncryptionKeyTypeAutoGenerated},
		},
		{
			name: "AWS with IMDS reads nothing",
			spec: couchbasev2.CouchbaseEncryptionKeySpec{
				KeyType: couchbasev2.CouchbaseEncryptionKeyTypeAWS,
				AWSKey:  &couchbasev2.CouchbaseEncryptionKeyAWS{UseIMDS: true},
			},
		},
		{
			name: "AWS with a credentials Secret",
			spec: couchbasev2.CouchbaseEncryptionKeySpec{
				KeyType: couchbasev2.CouchbaseEncryptionKeyTypeAWS,
				AWSKey:  &couchbasev2.CouchbaseEncryptionKeyAWS{CredentialsSecret: "aws-creds"},
			},
			wantPaths:   map[string]string{"credentialsFile": mountDir + "aws-creds-credentials"},
			wantSpecRef: "spec.awsKey.credentialsSecret",
		},
		{
			name: "KMIP without settings reads nothing",
			spec: couchbasev2.CouchbaseEncryptionKeySpec{KeyType: couchbasev2.CouchbaseEncryptionKeyTypeKMIP},
		},
		{
			name: "KMIP client certificate, key and passphrase",
			spec: couchbasev2.CouchbaseEncryptionKeySpec{
				KeyType: couchbasev2.CouchbaseEncryptionKeyTypeKMIP,
				KMIPKey: &couchbasev2.CouchbaseEncryptionKeyKMIP{ClientSecret: "kmip-client"},
			},
			wantPaths: map[string]string{
				"certPath": mountDir + "kmip-client-tls.crt",
				"keyPath":  mountDir + "kmip-client-tls.key",
			},
			wantValues:  []string{"passphrase"},
			wantSpecRef: "spec.kmipKey.clientSecret",
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			creds := CredentialsFor(&couchbasev2.CouchbaseEncryptionKey{Spec: tc.spec})

			// These names and paths are already in shadow Secrets and on the
			// server, so they must never change.
			paths := map[string]string{}

			for _, f := range creds.Files {
				paths[f.ServerField] = f.MountPath()

				assert.Equal(t, tc.wantSpecRef, f.SpecField)
			}

			if tc.wantPaths == nil {
				assert.Empty(t, paths)
			} else {
				assert.Equal(t, tc.wantPaths, paths)
			}

			values := []string{}

			for _, value := range creds.Values {
				values = append(values, value.DataKey)

				assert.Equal(t, tc.wantSpecRef, value.SpecField)
			}

			if tc.wantValues == nil {
				assert.Empty(t, values)
			} else {
				assert.Equal(t, tc.wantValues, values)
			}

			assert.ElementsMatch(t, keys(tc.wantPaths), creds.ServerFields())
		})
	}
}

func keys(m map[string]string) []string {
	out := []string{}

	for k := range m {
		out = append(out, k)
	}

	return out
}
