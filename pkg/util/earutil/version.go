package earutil

import (
	couchbasev2 "github.com/couchbase/couchbase-operator/pkg/apis/couchbase/v2"
	"github.com/couchbase/couchbase-operator/pkg/util/constants"
)

// MinimumServerVersionForKeyType is the first Couchbase Server release that
// supports the encryption key type. Admission rejects a key whose type is newer
// than the image of a cluster that selects it; the reconciler defers creating
// it until every node runs this release. New key types add a case here.
func MinimumServerVersionForKeyType(keyType couchbasev2.CouchbaseEncryptionKeyType) string {
	switch keyType {
	case couchbasev2.CouchbaseEncryptionKeyTypeAutoGenerated,
		couchbasev2.CouchbaseEncryptionKeyTypeAWS,
		couchbasev2.CouchbaseEncryptionKeyTypeKMIP:
		return constants.MinimumVersionForEncryptionAtRest
	}

	// Unknown types are rejected by the CRD enum and by convertEncryptionKey.
	return constants.MinimumVersionForEncryptionAtRest
}
