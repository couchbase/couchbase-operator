package cluster

import (
	"testing"

	couchbasev2 "github.com/couchbase/couchbase-operator/pkg/apis/couchbase/v2"
	"github.com/couchbase/couchbase-operator/pkg/util"
	"github.com/couchbase/couchbase-operator/pkg/util/couchbaseutil"

	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
)

const (
	testWaitBucket = "bucket"
	testWaitKey    = "key"
)

func testWaitEncryptionKey(usage *couchbasev2.CouchbaseEncryptionKeyUsage) *couchbasev2.CouchbaseEncryptionKey {
	return &couchbasev2.CouchbaseEncryptionKey{
		ObjectMeta: metav1.ObjectMeta{Name: testWaitKey},
		Spec: couchbasev2.CouchbaseEncryptionKeySpec{
			KeyType: couchbasev2.CouchbaseEncryptionKeyTypeAutoGenerated,
			Usage:   usage,
		},
	}
}

func testWaitServerKey(usage ...string) couchbaseutil.EncryptionKeyList {
	return couchbaseutil.EncryptionKeyList{{
		ID:            3,
		EncryptionKey: couchbaseutil.EncryptionKey{Name: testWaitKey, Usage: usage},
	}}
}

func TestEncryptionKeyWait(t *testing.T) {
	allBuckets := &couchbasev2.CouchbaseEncryptionKeyUsage{AllBuckets: true}
	thisBucket := &couchbasev2.CouchbaseEncryptionKeyUsage{Buckets: []string{testWaitBucket}}

	testcases := []struct {
		name           string
		encryption     *couchbasev2.BucketEncryptionAtRestConfiguration
		sample         bool
		keys           []*couchbasev2.CouchbaseEncryptionKey
		serverKeys     couchbaseutil.EncryptionKeyList
		expectWait     bool
		keyNamesBucket bool
	}{
		{
			name:       "no encryption does not wait",
			keys:       []*couchbasev2.CouchbaseEncryptionKey{testWaitEncryptionKey(allBuckets)},
			serverKeys: nil,
		},
		{
			name:       "empty key name does not wait",
			encryption: &couchbasev2.BucketEncryptionAtRestConfiguration{},
			keys:       []*couchbasev2.CouchbaseEncryptionKey{testWaitEncryptionKey(allBuckets)},
		},
		{
			name:       "key with no resource keeps the old fallback",
			encryption: &couchbasev2.BucketEncryptionAtRestConfiguration{KeyName: testWaitKey},
		},
		{
			name:       "sample bucket does not wait",
			encryption: &couchbasev2.BucketEncryptionAtRestConfiguration{KeyName: testWaitKey},
			sample:     true,
			keys:       []*couchbasev2.CouchbaseEncryptionKey{testWaitEncryptionKey(allBuckets)},
		},
		{
			name:       "key not on the server waits",
			encryption: &couchbasev2.BucketEncryptionAtRestConfiguration{KeyName: testWaitKey},
			keys:       []*couchbasev2.CouchbaseEncryptionKey{testWaitEncryptionKey(allBuckets)},
			expectWait: true,
		},
		{
			name:       "key with the default usage not on the server waits",
			encryption: &couchbasev2.BucketEncryptionAtRestConfiguration{KeyName: testWaitKey},
			keys:       []*couchbasev2.CouchbaseEncryptionKey{testWaitEncryptionKey(nil)},
			expectWait: true,
		},
		{
			name:       "server key not yet permitting the bucket waits",
			encryption: &couchbasev2.BucketEncryptionAtRestConfiguration{KeyName: testWaitKey},
			keys:       []*couchbasev2.CouchbaseEncryptionKey{testWaitEncryptionKey(allBuckets)},
			serverKeys: testWaitServerKey(couchbaseutil.EncryptionKeyUsageKEKEncryption),
			expectWait: true,
		},
		{
			name:       "server key permitting all buckets is ready",
			encryption: &couchbasev2.BucketEncryptionAtRestConfiguration{KeyName: testWaitKey},
			keys:       []*couchbasev2.CouchbaseEncryptionKey{testWaitEncryptionKey(allBuckets)},
			serverKeys: testWaitServerKey(couchbaseutil.EncryptionKeyUsageBucketEncryptionAll),
		},
		{
			name:       "server key permitting this bucket is ready",
			encryption: &couchbasev2.BucketEncryptionAtRestConfiguration{KeyName: testWaitKey},
			keys:       []*couchbasev2.CouchbaseEncryptionKey{testWaitEncryptionKey(thisBucket)},
			serverKeys: testWaitServerKey(couchbaseutil.BucketEncryptionUsage(testWaitBucket)),
		},
		{
			name:           "key naming the bucket is flagged so a new bucket is still created",
			encryption:     &couchbasev2.BucketEncryptionAtRestConfiguration{KeyName: testWaitKey},
			keys:           []*couchbasev2.CouchbaseEncryptionKey{testWaitEncryptionKey(thisBucket)},
			expectWait:     true,
			keyNamesBucket: true,
		},
	}

	for _, testcase := range testcases {
		t.Run(testcase.name, func(t *testing.T) {
			bucket := &couchbasev2.CouchbaseBucket{
				ObjectMeta: metav1.ObjectMeta{Name: testWaitBucket},
				Spec: couchbasev2.CouchbaseBucketSpec{
					SampleBucket:     testcase.sample,
					EncryptionAtRest: testcase.encryption,
				},
			}

			wait, waiting := encryptionKeyWait(bucket, testcase.keys, testcase.serverKeys)

			if waiting != testcase.expectWait {
				t.Fatalf("waiting: expected %v, got %v", testcase.expectWait, waiting)
			}

			if !waiting {
				return
			}

			if wait.keyName != testWaitKey || wait.reason == "" {
				t.Errorf("expected key %q and a reason, got %+v", testWaitKey, wait)
			}

			if wait.keyNamesBucket != testcase.keyNamesBucket {
				t.Errorf("keyNamesBucket: expected %v, got %v", testcase.keyNamesBucket, wait.keyNamesBucket)
			}
		})
	}
}

func TestKeepBucketEncryption(t *testing.T) {
	requested := couchbaseutil.Bucket{
		BucketName:                          testWaitBucket,
		BucketMemoryQuota:                   200,
		EncryptionAtRestKeyID:               util.IntPtr(-1),
		EncryptionAtRestDekLifetime:         util.IntPtr(0),
		EncryptionAtRestDekRotationInterval: util.IntPtr(0),
	}

	actual := couchbaseutil.Bucket{
		BucketName:                          testWaitBucket,
		BucketMemoryQuota:                   100,
		EncryptionAtRestKeyID:               util.IntPtr(3),
		EncryptionAtRestDekLifetime:         util.IntPtr(31536000),
		EncryptionAtRestDekRotationInterval: util.IntPtr(2592000),
	}

	keepBucketEncryption(&requested, &actual)

	if *requested.EncryptionAtRestKeyID != 3 || *requested.EncryptionAtRestDekLifetime != 31536000 || *requested.EncryptionAtRestDekRotationInterval != 2592000 {
		t.Errorf("expected the server's encryption settings, got key %d lifetime %d rotation %d",
			*requested.EncryptionAtRestKeyID, *requested.EncryptionAtRestDekLifetime, *requested.EncryptionAtRestDekRotationInterval)
	}

	if requested.BucketMemoryQuota != 200 {
		t.Errorf("expected other settings to be left as requested, got memory quota %d", requested.BucketMemoryQuota)
	}
}
