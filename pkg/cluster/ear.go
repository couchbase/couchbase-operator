// encryptionKeyDependency returns the name of the encryption key that key
// depends on (via AutoGenerated.EncryptWithKey), or "" if it has no
// dependency. orderKeysForCreation guarantees parents are processed before
// dependents in the same loop, so checking only the direct dependency is
// sufficient: if a transitive ancestor was deferred, the direct parent
// will also have been deferred in an earlier iteration.
func encryptionKeyDependency(key *couchbasev2.CouchbaseEncryptionKey) string {
	if key.Spec.KeyType != couchbasev2.CouchbaseEncryptionKeyTypeAutoGenerated {
		return ""
	}

	if key.Spec.AutoGenerated == nil {
		return ""
	}

	return key.Spec.AutoGenerated.EncryptWithKey
}

// credentialFilePendingMessage is what the server says about a credential path
// whose file it cannot read.
const credentialFilePendingMessage = "must be a valid file"

// isCredentialFilePendingError reports whether err is a transient CBS
// rejection because a credential file referenced by the encryption key
// is not yet visible on the target pod's filesystem. This occurs in the
// gap between the operator writing the shadow Secret and kubelet projecting
// its contents onto the pod. The next reconcile cycle will retry once the
// file is available. serverFields are the request fields that carry file
// paths for this key.
func isCredentialFilePendingError(err error, serverFields []string) bool {
	var fre couchbaseutil.FailedRequestError
	if !goerrors.As(err, &fre) {
		return false
	}

	if fre.StatusCode != http.StatusBadRequest {
		return false
	}

	if !strings.Contains(fre.Body, credentialFilePendingMessage) {
		return false
	}

	for _, field := range serverFields {
		// Quoted, so that a field name inside another word does not match.
		if strings.Contains(fre.Body, `"`+field+`"`) {
			return true
		}
	}

	return false
}

func (c *Cluster) reconcileEncryptionAtRest() error {
	if !c.IsEncryptionAtRestManaged() {
		return nil
	}

	// Handle rotate encryption key annotation trigger
	if err := c.reconcileRotateEncryptionKey(); err != nil {
		return err
	}

	// Handle drop DEK bucket annotation trigger
	if err := c.reconcileDropDEKBucket(); err != nil {
		return err
	}

	// Handle drop DEK system annotation trigger
	if err := c.reconcileDropDEKSystem(); err != nil {
		return err
	}

	encryptionKeys := &couchbaseutil.EncryptionKeyList{}
	if err := couchbaseutil.ListEncryptionKeys(encryptionKeys).On(c.api, c.readyMembers()); err != nil {
		return err
	}

	for _, settingsType := range earutil.SettingsTypes {
		if err := c.reconcileEncryptionAtRestSettings(*encryptionKeys, settingsType); err != nil {
			return err
		}
	}

	return nil
}

// reconcileRotateEncryptionKey handles the annotation driven rotation of encryption keys.
func (c *Cluster) reconcileRotateEncryptionKey() error {
	if c.cluster.Annotations == nil {
		return nil
	}

	keyList, found := c.cluster.Annotations[constants.AnnotationRotateEncryptionKey]
	if !found || strings.TrimSpace(keyList) == "" {
		return nil
	}

	keys := strings.Split(keyList, ",")
	var failedKeys []string

	for _, key := range keys {
		key = strings.TrimSpace(key)
		if key == "" {
			continue
		}

		keyID, err := strconv.Atoi(key)
		if err != nil {
			c.log.Error(err, "Invalid encryption key ID",
				"cluster", c.namespacedName(),
				"keyID", key)
			failedKeys = append(failedKeys, key)
			continue
		}

		req := couchbaseutil.RotateEncryptionKey(keyID)
		err = req.On(c.api, c.readyMembers())
		if err != nil {
			failedKeys = append(failedKeys, key)

			c.log.Error(err, "Failed to rotate encryption key",
				"cluster", c.namespacedName(),
				"keyID", key)

			continue
		}

		c.log.Info("Rotated encryption key",
			"cluster", c.namespacedName(),
			"keyID", key)
	}

	// Update annotation based on result
	if len(failedKeys) == 0 {
		delete(c.cluster.Annotations, constants.AnnotationRotateEncryptionKey)

		c.log.Info("Removed rotate encryption key annotation after successful operation",
			"cluster", c.namespacedName())
	} else {
		// retry only failed keys
		c.cluster.Annotations[constants.AnnotationRotateEncryptionKey] =
			strings.Join(failedKeys, ",")

		c.log.Info("Some encryption key rotations failed, will retry",
			"cluster", c.namespacedName(),
			"failedKeys", failedKeys)
	}

	_, err := c.k8s.CouchbaseClient.
		CouchbaseV2().
		CouchbaseClusters(c.cluster.Namespace).
		Update(context.Background(), c.cluster, metav1.UpdateOptions{})

	if err != nil {
		c.log.Error(err, "Failed to update rotate encryption key annotation",
			"cluster", c.namespacedName())
		return err
	}

	return nil
}

